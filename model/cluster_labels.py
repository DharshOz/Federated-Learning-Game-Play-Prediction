"""
cluster_labels.py — Unsupervised clustering of real (human) match data.

Assigns pseudo-labels (cluster_id) to real player matches that have no persona ground truth.
These cluster IDs are saved alongside each match's features for comparison with the
neural network predictions in train_centralized.py (Adjusted Rand Index sanity check).

Steps:
  1. Load all real (non-bot) match feature vectors from extract_features.build_feature_dataset()
  2. Standardize features (StandardScaler, fit on all real data)
  3. Run KMeans with k=4 (matching the 4 persona archetypes)
  4. Run silhouette analysis for k=2..6 to report the best k
  5. Save cluster assignments as 'cluster_id' column in a CSV
  6. Print top-5 highest-magnitude feature weights distinguishing each cluster

Usage:
    python cluster_labels.py
    python cluster_labels.py --logs-dir ./logs --out cluster_assignments.csv
"""

import os
import sys
import argparse
import warnings

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")

import numpy as np
import pandas as pd

_BASE_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _BASE_DIR)

from extract_features import build_feature_dataset, HERO_MAX_HP

warnings.filterwarnings("ignore", category=FutureWarning)

# ─── Constants ────────────────────────────────────────────────────────────────
DEFAULT_LOGS_DIR  = os.path.join(_BASE_DIR, "logs")
DEFAULT_OUT_CSV   = os.path.join(_BASE_DIR, "cluster_assignments.csv")
EXCLUDE_COLS      = {"outcome_won"}   # label — never a model feature
K_FIXED           = 4                 # matching 4 persona archetypes
K_RANGE           = range(2, 7)       # silhouette analysis range


# ─── Helpers ─────────────────────────────────────────────────────────────────

def get_feature_columns(df: pd.DataFrame) -> list:
    """Return model-input feature columns (exclude metadata and outcome label)."""
    meta_cols   = [c for c in df.columns if c.startswith("_")]
    label_cols  = list(EXCLUDE_COLS)
    extra_meta  = ["persona_label", "cluster_id"]
    skip        = set(meta_cols + label_cols + extra_meta)
    return [c for c in df.columns if c not in skip]


def is_bot_match(player_id: str) -> bool:
    """Return True if this player_id was generated by a persona bot."""
    return str(player_id).startswith("bot_")


# ─── Main clustering routine ─────────────────────────────────────────────────

def run_clustering(
    logs_dir: str = DEFAULT_LOGS_DIR,
    out_csv:  str = DEFAULT_OUT_CSV,
    seed: int = 42,
) -> pd.DataFrame:
    """
    Load real match features, cluster them, save cluster_id assignments.

    Returns the real-match DataFrame with an added 'cluster_id' column.
    """
    from sklearn.cluster import KMeans
    from sklearn.preprocessing import StandardScaler
    from sklearn.metrics import silhouette_score

    # ── 1. Load all matches (bot + real) ─────────────────────────────────────
    print(f"Loading matches from: {logs_dir}")
    df_all = build_feature_dataset(logs_dir, add_bigrams=True)
    print(f"  Total matches loaded: {len(df_all)}")

    # ── 2. Split real vs bot ──────────────────────────────────────────────────
    mask_bot  = df_all["_player_id"].apply(is_bot_match)
    df_real   = df_all[~mask_bot].copy().reset_index(drop=True)
    df_bot    = df_all[ mask_bot].copy().reset_index(drop=True)

    print(f"  Bot matches   : {len(df_bot)}")
    print(f"  Real matches  : {len(df_real)}")

    if len(df_real) == 0:
        print("\n[cluster_labels] WARNING: No real (non-bot) matches found.")
        print("  Run the game first to generate human play logs, or run persona_bots.py.")
        print("  Saving empty CSV and returning.")
        empty = pd.DataFrame(columns=["_match_id", "_player_id", "cluster_id"])
        empty.to_csv(out_csv, index=False)
        return empty

    feat_cols = get_feature_columns(df_real)
    print(f"  Feature columns: {len(feat_cols)}")

    X_real = df_real[feat_cols].fillna(0).values.astype(np.float32)

    # ── 3. Standardize ────────────────────────────────────────────────────────
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X_real)

    # ── 4. Silhouette analysis for k=2..6 ─────────────────────────────────────
    print(f"\n{'─'*50}")
    print("Silhouette Analysis (k=2..6):")
    print(f"{'─'*50}")
    sil_scores = {}
    for k in K_RANGE:
        if len(df_real) < k:
            print(f"  k={k}: not enough samples ({len(df_real)}), skipping")
            continue
        km = KMeans(n_clusters=k, random_state=seed, n_init=10)
        labels_k = km.fit_predict(X_scaled)
        if len(set(labels_k)) < 2:
            sil_scores[k] = -1.0
        else:
            sil_scores[k] = silhouette_score(X_scaled, labels_k)
        print(f"  k={k}: silhouette = {sil_scores[k]:.4f}")

    best_k = max(sil_scores, key=sil_scores.get) if sil_scores else K_FIXED
    print(f"\n  Best k by silhouette: {best_k}  (score: {sil_scores.get(best_k, 'N/A'):.4f})")
    print(f"  Using k={K_FIXED} (fixed to match 4 persona archetypes) for assignments.")

    # ── 5. KMeans with k=4 ────────────────────────────────────────────────────
    kmeans_k4 = KMeans(n_clusters=K_FIXED, random_state=seed, n_init=20, max_iter=500)
    cluster_ids = kmeans_k4.fit_predict(X_scaled)
    df_real["cluster_id"] = cluster_ids

    print(f"\n{'─'*50}")
    print(f"KMeans (k={K_FIXED}) cluster sizes:")
    for c in range(K_FIXED):
        size = (cluster_ids == c).sum()
        print(f"  Cluster {c}: {size} matches")

    # ── 6. Top 5 distinguishing features per cluster ──────────────────────────
    print(f"\n{'─'*50}")
    print("Top 5 distinguishing features per cluster (centroid vs global mean):")
    print("(Use these to manually name clusters, e.g. cluster 2 → 'Aggressive-like')")
    print(f"{'─'*50}")

    centroids = kmeans_k4.cluster_centers_   # shape (k, n_features)
    global_mean = X_scaled.mean(axis=0)
    feat_arr = np.array(feat_cols)

    for c in range(K_FIXED):
        delta = centroids[c] - global_mean
        top_idx = np.argsort(np.abs(delta))[::-1][:5]
        print(f"\n  Cluster {c} ({(cluster_ids == c).sum()} matches) top features:")
        for rank, idx in enumerate(top_idx, 1):
            sign = "↑" if delta[idx] > 0 else "↓"
            print(f"    {rank}. {feat_arr[idx]:40s}  delta={delta[idx]:+.3f} {sign}")

    # ── 7. Save cluster assignments ───────────────────────────────────────────
    out_df = df_real[["_match_id", "_player_id", "cluster_id"]].copy()
    # Also save all features for downstream comparison
    result_df = df_real.copy()
    result_df.to_csv(out_csv, index=False)
    print(f"\nCluster assignments saved to: {out_csv}")
    print(f"  Rows: {len(result_df)}  |  Columns: {len(result_df.columns)}")

    return result_df


# ─── Entry point ──────────────────────────────────────────────────────────────

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Cluster real match data for pseudo-labels")
    parser.add_argument("--logs-dir", default=DEFAULT_LOGS_DIR,
                        help=f"Path to logs directory (default: {DEFAULT_LOGS_DIR})")
    parser.add_argument("--out", default=DEFAULT_OUT_CSV,
                        help=f"Output CSV path (default: {DEFAULT_OUT_CSV})")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    run_clustering(logs_dir=args.logs_dir, out_csv=args.out, seed=args.seed)
